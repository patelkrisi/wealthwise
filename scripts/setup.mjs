// One-time local setup: creates .env.local with a random AUTH_SECRET, CRON_SECRET and VAPID keys for web push.
import fs from 'node:fs';
import crypto from 'node:crypto';
import webpush from 'web-push';
if (fs.existsSync('.env.local')) {
  console.log('.env.local already exists — leaving it alone.');
  process.exit(0);
}
const v = webpush.generateVAPIDKeys();
const env = `# Generated by npm run setup — see .env.example for every option
AUTH_SECRET=${crypto.randomBytes(32).toString('hex')}
CRON_SECRET=${crypto.randomBytes(16).toString('hex')}
VAPID_PUBLIC_KEY=${v.publicKey}
VAPID_PRIVATE_KEY=${v.privateKey}
VAPID_SUBJECT=mailto:you@example.com

# Add your Claude API key (console.anthropic.com) to switch parsing, chat, insights & summaries to Claude:
# ANTHROPIC_API_KEY=sk-ant-...
`;
fs.writeFileSync('.env.local', env);
console.log('Created .env.local (AUTH_SECRET, CRON_SECRET, VAPID keys). Add ANTHROPIC_API_KEY when you have one.');
